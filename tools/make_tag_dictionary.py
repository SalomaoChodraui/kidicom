#!/usr/bin/env python3
"""Builds Sources/KidicomKit/DICOM/TagNames.swift from dcmtk's dicom.dic.

Usage: tools/make_tag_dictionary.py /opt/homebrew/share/dcmtk-*/dicom.dic
Keeps standard tags with a plain (gggg,eeee) key; writes one string literal
"GGGGEEEE VR Keyword" per line, parsed lazily at run time.
"""
import re, sys

lines = []
for line in open(sys.argv[1], encoding="latin-1"):
    if not line.startswith("("):
        continue
    parts = line.rstrip("\n").split("\t")
    tag, vr, keyword = parts[0], parts[1], parts[2]
    m = re.fullmatch(r"\(([0-9A-F]{4}),([0-9A-F]{4})\)", tag)
    if not m or keyword.startswith("RETIRED_") or keyword.startswith("ACR_NEMA"):
        continue
    vr = vr.split("/")[0][:2]
    lines.append(f"{m.group(1)}{m.group(2)} {vr} {keyword}")

body = "\n".join(lines)
out = f'''// Generated by tools/make_tag_dictionary.py from dcmtk's dicom.dic
// (names from the DICOM standard, PS3.6). Do not edit by hand.

enum TagNames {{
    static let table = """
{body}
"""
}}
'''
open("Sources/KidicomKit/DICOM/TagNames.swift", "w").write(out)
print(len(lines), "tags")
